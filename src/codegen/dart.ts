/**
 * Schema-snapshot → Dart code generation (`vb-types --lang dart`).
 *
 * Output: one `.dart` file for `package:vaultbase` with, per collection,
 *   - `XRecord extends RecordModel`, a typed getter per field;
 *   - `XCreate` (base and auth collections), the fields to create a record
 *     with and a `toJson()` for `create()`;
 * plus `vb.collections.<name>`, each collection with its record type.
 */

import type { SnapshotCollection, SnapshotField, SnapshotShape } from "./generate.ts";

export interface DartOptions {
  /** Header text — defaults to a do-not-edit banner. */
  header?: string;
}

const DEFAULT_HEADER = `// AUTO-GENERATED by \`vb-types --lang dart\`. Do not edit.\n`;

const KEYWORDS = new Set([
  "abstract", "as", "assert", "async", "await", "base", "break", "case", "catch", "class",
  "const", "continue", "covariant", "default", "deferred", "do", "dynamic", "else", "enum",
  "export", "extends", "extension", "external", "factory", "false", "final", "finally", "for",
  "Function", "get", "hide", "if", "implements", "import", "in", "interface", "is", "late",
  "library", "mixin", "new", "null", "of", "on", "operator", "part", "required", "rethrow",
  "return", "sealed", "set", "show", "static", "super", "switch", "sync", "this", "throw",
  "true", "try", "type", "typedef", "var", "void", "when", "while", "with", "yield",
]);

/** Members of RecordModel and Object a field getter must not shadow. */
const RECORD_MEMBERS = new Set([
  "id", "created", "updated", "createdAt", "updatedAt", "data", "getString", "getInt",
  "getDouble", "getBool", "getList", "getDate", "expandOne", "expandMany", "toJson",
  "toString", "hashCode", "runtimeType", "noSuchMethod",
  // Emitted for every auth collection.
  "email", "emailVerified", "totpEnabled", "isAnonymous",
]);

export function generateDart(snapshot: SnapshotShape, opts: DartOptions = {}): string {
  const header = opts.header ?? DEFAULT_HEADER;
  const classes: string[] = [];
  const accessors: string[] = [];
  const accessorNames = new Set<string>(["vb", "hashCode", "runtimeType", "toString", "noSuchMethod"]);
  const classNames = new Set<string>(["Vaultbase"]);
  let usesGeo = false;

  for (const col of snapshot.collections) {
    if (!/^[A-Za-z_][A-Za-z0-9_]{0,62}$/.test(col.name)) continue;
    const fields = parseFields(col.fields).filter((f) => keepField(f, col));
    const base = unique(pascal(col.name), classNames);
    const names = fieldNames(fields, col.type === "auth" ? RECORD_MEMBERS : withoutAuth(RECORD_MEMBERS));
    usesGeo ||= fields.some((f) => f.type === "geoPoint");

    const accessor = unique(safeIdent(camel(col.name)), accessorNames);
    classes.push(emitRecord(`${base}Record`, col, fields, names));
    if (col.type === "base" || col.type === "auth") {
      classes.push(emitCreate(`${base}Create`, col, fields.filter((f) => f.type !== "autodate"), names, accessor));
    }

    const quoted = dartString(col.name);
    accessors.push(col.type === "singleton"
      ? `  Singleton<${base}Record> get ${accessor} =>\n      vb.singletonOf(${quoted}, ${base}Record.fromJson);`
      : `  Collection<${base}Record> get ${accessor} =>\n      vb.collectionOf(${quoted}, ${base}Record.fromJson);`);
  }

  const parts = [
    header.trimEnd(),
    "// ignore_for_file: type=lint",
    "",
    "import 'package:vaultbase/vaultbase.dart';",
    "",
    classes.join("\n\n"),
    "",
    "/// Each collection with its record type: `vb.collections.posts.list()`.",
    "class VaultbaseCollections {",
    "  const VaultbaseCollections(this.vb);",
    "",
    "  final Vaultbase vb;",
    ...(accessors.length ? ["", accessors.join("\n\n")] : []),
    "}",
    "",
    "extension VaultbaseSchema on Vaultbase {",
    "  VaultbaseCollections get collections => VaultbaseCollections(this);",
    "}",
  ];
  if (usesGeo) {
    parts.push(
      "",
      "({double lat, double lng})? _geoPoint(Object? v) => v is Map &&",
      "        v['lat'] is num &&",
      "        v['lng'] is num",
      "    ? (lat: (v['lat'] as num).toDouble(), lng: (v['lng'] as num).toDouble())",
      "    : null;",
    );
  }
  parts.push("");
  return parts.join("\n");
}

function parseFields(raw: string | SnapshotField[]): SnapshotField[] {
  if (Array.isArray(raw)) return raw;
  try { return JSON.parse(raw) as SnapshotField[]; } catch { return []; }
}

function keepField(f: SnapshotField, col: SnapshotCollection): boolean {
  if (f.system || f.type === "password") return false;
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(f.name)) return false;
  if (["id", "created", "updated"].includes(f.name)) return false;
  // Emitted for every auth collection; snapshots also list them as implicit fields.
  if (col.type === "auth" && ["email", "password", "verified", "email_verified"].includes(f.name)) return false;
  return true;
}

function withoutAuth(s: Set<string>): Set<string> {
  const out = new Set(s);
  for (const n of ["email", "emailVerified", "totpEnabled", "isAnonymous"]) out.delete(n);
  return out;
}

/** Dart names for the fields, shared by the record and create classes. */
function fieldNames(fields: SnapshotField[], reserved: Set<string>): Map<string, string> {
  const taken = new Set<string>();
  const out = new Map<string, string>();
  for (const f of fields) {
    let n = safeIdent(camel(f.name));
    if (reserved.has(n)) n = `${n}Field`;
    out.set(f.name, unique(n, taken));
  }
  return out;
}

function emitRecord(name: string, col: SnapshotCollection, fields: SnapshotField[], names: Map<string, string>): string {
  const lines = [
    `/// A record of \`${col.name}\`.`,
    `class ${name} extends RecordModel {`,
    `  ${name}(super.data);`,
    "",
    `  factory ${name}.fromJson(Map<String, dynamic> json) => ${name}(json);`,
  ];
  if (col.type === "auth") {
    lines.push(
      "",
      "  String get email => getString('email');",
      "",
      "  bool get emailVerified => getBool('email_verified');",
      "",
      "  bool get totpEnabled => getBool('totp_enabled');",
      "",
      "  bool get isAnonymous => getBool('is_anonymous');",
    );
  }
  for (const f of fields) {
    // A singleton's record starts with every field empty, required or not.
    const required = !!f.required && col.type !== "singleton";
    lines.push("", `  ${readType(f, required)} get ${names.get(f.name)} => ${readExpr(f, required)};`);
  }
  lines.push("}");
  return lines.join("\n");
}

function emitCreate(
  name: string, col: SnapshotCollection, fields: SnapshotField[], names: Map<string, string>, accessor: string,
): string {
  const params: string[] = [];
  const members: string[] = [];
  const json: string[] = [];
  if (col.type === "auth") {
    params.push("required this.email", "required this.password");
    members.push("final String email;", "final String password;");
    json.push("'email': email", "'password': password");
  }
  for (const f of fields) {
    const n = names.get(f.name)!;
    const key = dartString(f.name);
    const t = writeType(f);
    params.push(f.required ? `required this.${n}` : `this.${n}`);
    members.push(`final ${f.required ? t : `${t}?`} ${n};`);
    const v = writeExpr(f, f.required ? n : `${n}!`);
    json.push(f.required ? `${key}: ${v}` : `if (${n} != null) ${key}: ${v}`);
  }
  // Auth records are made by signing up, never by a plain create.
  const usage = col.type === "auth"
    ? [`/// Fields for a new \`${col.name}\` account:`,
       `/// \`auth.collection(${dartString(col.name)}).register(u.email, u.password, data: u.toJson())\`.`]
    : [`/// Fields for a new \`${col.name}\` record:`,
       `/// \`collections.${accessor}.create(${name}(...).toJson())\`.`];
  const lines = [...usage, `class ${name} {`];
  lines.push(params.length ? `  const ${name}({${params.join(", ")}});` : `  const ${name}();`);
  for (const m of members) lines.push("", `  ${m}`);
  lines.push("", `  Map<String, dynamic> toJson() => {${json.join(", ")}};`, "}");
  return lines.join("\n");
}

function isList(f: SnapshotField): boolean {
  const multiple = (f.options as { multiple?: boolean } | undefined)?.multiple === true;
  return f.type === "vector" || ((f.type === "select" || f.type === "file") && multiple);
}

function readType(f: SnapshotField, required: boolean): string {
  if (isList(f)) return f.type === "vector" ? "List<double>" : "List<String>";
  switch (f.type) {
    case "date":
    case "autodate":
      return "DateTime?";
    case "json":
      return "Object?";
    case "geoPoint":
      return "({double lat, double lng})?";
    default: {
      const t = scalar(f);
      return required && t !== "Object" ? t : `${t}?`;
    }
  }
}

function scalar(f: SnapshotField): string {
  switch (f.type) {
    case "number": return "num";
    case "bool": return "bool";
    case "text": case "email": case "url": case "editor": case "relation":
    case "color": case "select": case "file": case "password":
      return "String";
    default: return "Object";
  }
}

function readExpr(f: SnapshotField, required: boolean): string {
  const key = dartString(f.name);
  if (isList(f)) {
    return f.type === "vector"
      ? `[for (final v in getList<num>(${key})) v.toDouble()]`
      : `getList<String>(${key})`;
  }
  switch (f.type) {
    case "date":
    case "autodate":
      return `getDate(${key})`;
    case "json":
      return `data[${key}]`;
    case "geoPoint":
      return `_geoPoint(data[${key}])`;
  }
  const t = scalar(f);
  if (t === "Object") return `data[${key}]`;
  if (required) {
    if (t === "String") return `getString(${key})`;
    if (t === "bool") return `getBool(${key})`;
    return `data[${key}] as num? ?? 0`;
  }
  if (t === "bool") return `data[${key}] == null ? null : getBool(${key})`;
  return `data[${key}] as ${t}?`;
}

function writeType(f: SnapshotField): string {
  if (isList(f)) return f.type === "vector" ? "List<double>" : "List<String>";
  switch (f.type) {
    case "date": return "DateTime";
    case "json": return "Object";
    case "geoPoint": return "({double lat, double lng})";
    default: return scalar(f);
  }
}

function writeExpr(f: SnapshotField, v: string): string {
  switch (f.type) {
    case "date": return `${v}.toUtc().toIso8601String()`;
    case "geoPoint": return `{'lat': ${v}.lat, 'lng': ${v}.lng}`;
    default: return v;
  }
}

function camel(s: string): string {
  const parts = s.split(/[^A-Za-z0-9]+/).filter(Boolean);
  if (parts.length === 0) return "field";
  const [first, ...rest] = parts;
  const head = first![0]!.toLowerCase() + first!.slice(1);
  return head + rest.map((p) => p[0]!.toUpperCase() + p.slice(1)).join("");
}

function pascal(s: string): string {
  const c = camel(s);
  return c[0]!.toUpperCase() + c.slice(1);
}

/** A Dart identifier: not a keyword, not starting with a digit or `_`. */
function safeIdent(s: string): string {
  let n = /^[0-9]/.test(s) ? `f${s}` : s;
  if (KEYWORDS.has(n)) n = `${n}Field`;
  return n;
}

function unique(n: string, taken: Set<string>): string {
  let out = n;
  for (let i = 2; taken.has(out); i++) out = `${n}${i}`;
  taken.add(out);
  return out;
}

function dartString(s: string): string {
  return `'${s.replace(/\\/g, "\\\\").replace(/'/g, "\\'").replace(/\$/g, "\\$")}'`;
}
